/**
 * Emit public/_redirects from the single redirect maps used by Node + CF.
 * Cloudflare Workers assets constraints:
 * - Source paths must be relative (no https://host/…)
 * - Max 100 static redirect rules
 * Node serve.mjs still uses the full PATH_REDIRECTS / CHECKOUT maps.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { PATH_REDIRECTS } from '../src/config/path-redirects.mjs';
import { CHECKOUT_PATH_REDIRECTS } from '../src/config/checkout-redirects.mjs';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const outFile = path.join(root, 'public', '_redirects');
const CF_REDIRECT_LIMIT = 100;

/** True when the only change is adding a trailing slash (html_handling covers these). */
function isTrailingSlashOnly(from, to) {
  return from !== '/' && !from.endsWith('/') && `${from}/` === to;
}

/**
 * Prefer slash forms so force-trailing-slash → exact rule.
 * Drop slash-only no-ops to stay under CF's 100-rule cap.
 */
function cfPathRedirects() {
  const byDest = new Map();
  for (const [from, to] of PATH_REDIRECTS) {
    if (isTrailingSlashOnly(from, to)) continue;
    const key = from.endsWith('/') ? from : `${from}/`;
    // Prefer the slash-form source when both exist.
    if (!byDest.has(key) || from.endsWith('/')) {
      byDest.set(key, to);
    }
  }
  return [...byDest.entries()].sort(([a], [b]) => a.localeCompare(b));
}

function cfCheckoutRedirects() {
  const byDest = new Map();
  for (const [from, to] of CHECKOUT_PATH_REDIRECTS) {
    const key = from.endsWith('/') ? from : `${from}/`;
    byDest.set(key, to);
  }
  return [...byDest.entries()].sort(([a], [b]) => a.localeCompare(b));
}

const pathRules = cfPathRedirects();
const checkoutRules = cfCheckoutRedirects();
const total = pathRules.length + checkoutRules.length;

if (total > CF_REDIRECT_LIMIT) {
  console.error(
    `write-redirects: ${total} rules exceeds Cloudflare limit of ${CF_REDIRECT_LIMIT}. Trim PATH_REDIRECTS.`,
  );
  process.exit(1);
}

const lines = [
  '# Generated by scripts/write-redirects.mjs — do not edit by hand.',
  '# CF Workers: relative sources only, ≤100 rules. Host www/http→https is Node serve / CF dashboard.',
  '# Full maps (incl. non-slash sources): path-redirects.mjs + checkout-redirects.mjs.',
  '',
  '# Path redirects (301 → final URL)',
];

for (const [from, to] of pathRules) {
  lines.push(`${from} ${to} 301`);
}

lines.push('', '# Checkout hops (302 → Zadeyo)');
for (const [from, to] of checkoutRules) {
  lines.push(`${from} ${to} 302`);
}

lines.push('');
fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, lines.join('\n'), 'utf8');
console.log(`Wrote ${outFile} (${pathRules.length} path + ${checkoutRules.length} checkout = ${total} rules)`);
